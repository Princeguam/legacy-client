import assert from "node:assert/strict";
import { readFile, writeFile } from "node:fs/promises";

const base = new URL("../src/design-system/", import.meta.url);
const tokens = JSON.parse(await readFile(new URL("tokens.json", base), "utf8"));
const guide = await readFile(
    new URL("../Legacy Wealth Design System/Agent Guide.md", import.meta.url),
    "utf8",
);
const check = process.argv.includes("--check");
const rem = (px) => `${px / 16}rem`;
const declarations = (values, prefix, format = String) =>
    Object.entries(values)
        .map(([key, value]) => `  --lwc-${prefix}-${key}: ${format(value)};`)
        .join("\n");

// Validate against the supplied source so regeneration cannot silently change colours.
for (const theme of ["light", "dark"]) {
    const section = guide
        .split(`### ${theme} semantic colour roles`)[1]
        .split(/\n##/)[0];
    const expected = Object.fromEntries(
        [...section.matchAll(/^- ([\w/-]+): (#[A-F0-9]{6})/gm)].map(
            ([, key, value]) => [key.replaceAll("/", "-"), value],
        ),
    );
    assert.deepEqual(
        tokens.themes[theme],
        expected,
        `${theme} colours must match the approved guide`,
    );
}
assert.equal(Object.keys(tokens.typography).length, 9);
assert.equal(tokens.brand["700"], "#005250");
assert.deepEqual(tokens.brand, Object.fromEntries([...guide.matchAll(/^- brand\/(\d+): (#[A-F0-9]{6})/gm)].map(([, key, value]) => [key, value])));
assert.deepEqual(tokens.radius, [0, 4, 8, 12, 16, 999]);
assert.deepEqual(tokens.duration, { instant: 0, fast: 100, standard: 180, enter: 240, exit: 160, complex: 320 });
assert.deepEqual(tokens.easing, { standard: [0.2, 0, 0, 1], enter: [0, 0, 0, 1], exit: [0.4, 0, 1, 1], linear: [0, 0, 1, 1] });
assert.deepEqual(tokens.space, [0, 8, 16, 24, 32, 40, 48, 64, 80, 96, 128]);
assert.deepEqual(tokens.breakpoints, {
    xs: 0,
    sm: 600,
    md: 960,
    lg: 1280,
    xl: 1600,
});

const aliasMap = {
    background: "background-canvas",
    foreground: "text-primary",
    card: "surface-default",
    "card-foreground": "text-primary",
    popover: "surface-default",
    "popover-foreground": "text-primary",
    primary: "action-default",
    "primary-foreground": "action-on",
    secondary: "secondary-default",
    "secondary-foreground": "secondary-on",
    muted: "surface-raised",
    "muted-foreground": "text-muted",
    accent: "selection-default",
    "accent-foreground": "text-primary",
    destructive: "status-danger-text",
    "destructive-foreground": "status-danger-background",
    border: "border-subtle",
    input: "border-control",
    ring: "focus-ring",
    "chart-1": "chart-primary",
    "chart-2": "chart-secondary",
    sidebar: "surface-default",
    "sidebar-foreground": "text-primary",
    "sidebar-primary": "action-default",
    "sidebar-primary-foreground": "action-on",
    "sidebar-accent": "selection-default",
    "sidebar-accent-foreground": "text-primary",
    "sidebar-border": "border-subtle",
    "sidebar-ring": "focus-ring",
};
let css =
    "/* Generated by scripts/design-system.mjs from tokens.json. Do not edit directly. */\n:root {\n";
css += declarations(tokens.brand, "brand") + "\n";
css +=
    declarations(
        Object.fromEntries(tokens.space.map((v) => [v, v])),
        "space",
        rem,
    ) + "\n";
css +=
    declarations(
        Object.fromEntries(tokens.radius.map((v) => [v, v])),
        "radius",
        (v) => `${v}px`,
    ) + "\n";
css += declarations(tokens.duration, "duration", (v) => `${v}ms`) + "\n";
css +=
    declarations(
        tokens.easing,
        "ease",
        (v) => `cubic-bezier(${v.join(", ")})`,
    ) + "\n";
css += declarations(tokens.dimensions, "dimension", rem) + "\n";
css +=
    '  --lwc-font-interface: "Inter", system-ui, sans-serif;\n  --lwc-font-financial: "IBM Plex Mono", ui-monospace, monospace;\n';
for (const [name, value] of Object.entries(tokens.typography)) {
    css += `  --lwc-type-${name}-size: ${rem(value.size)};\n  --lwc-type-${name}-line: ${value.line / value.size};\n  --lwc-type-${name}-weight: ${value.weight};\n`;
}
css +=
    "  --lwc-grid-columns: 4;\n  --lwc-grid-margin: 1rem;\n  --lwc-grid-gap: 1rem;\n  --radius: var(--lwc-radius-8);\n}\n";
for (const [name, colors] of Object.entries(tokens.themes)) {
    css += `${name === "light" ? ":root, " : ""}[data-theme="${name}"] {\n  color-scheme: ${name};\n${declarations(colors, "color")}\n`;
    css +=
        Object.entries(aliasMap)
            .map(([key, role]) => `  --${key}: var(--lwc-color-${role});`)
            .join("\n") + "\n}\n";
}
for (const [name, { size, line, weight }] of Object.entries(
    tokens.typography,
)) {
    css += `.type-${name} { font-size: var(--lwc-type-${name}-size); line-height: var(--lwc-type-${name}-line); font-weight: var(--lwc-type-${name}-weight); }\n`;
    assert.match(
        guide,
        new RegExp(
            `${name[0].toUpperCase() + name.slice(1)}: ${size}px / ${line}px, \\w+ ${weight}`,
        ),
    );
}
for (const [width, columns, margin, gap] of [
    [600, 8, 24, 24],
    [960, 12, 32, 24],
    [1280, 12, 32, 24],
    [1600, 12, 48, 32],
]) {
    css += `@media (min-width: ${width}px) { :root { --lwc-grid-columns: ${columns}; --lwc-grid-margin: ${rem(margin)}; --lwc-grid-gap: ${rem(gap)}; } }\n`;
}
css +=
    "@media (max-width: 599px) { :root { --lwc-type-hero-size: 2rem; --lwc-type-hero-line: 1.25; } }\n";
css +=
    "@media (prefers-reduced-motion: reduce) { :root {\n" +
    declarations(
        Object.fromEntries(Object.keys(tokens.duration).map((k) => [k, 0])),
        "duration",
        (v) => `${v}ms`,
    ) +
    "\n} }\n";

const components = [
    ...guide.matchAll(/### (\d{2})\. (.+)\n([\s\S]*?)(?=\n###|\n## |$)/g),
].map(([, id, name, body]) => ({
    id,
    name,
    purpose: body.split("\n")[0],
    ...Object.fromEntries(
        [...body.matchAll(/^- ([^:]+): (.+)/gm)].map(([, key, value]) => [
            key,
            value,
        ]),
    ),
}));
assert.equal(components.length, 30);
const manifest =
    JSON.stringify(
        {
            source: tokens.meta.source,
            version: tokens.meta.version,
            componentCount: 30,
            components,
        },
        null,
        2,
    ) + "\n";
for (const [name, content] of [
    ["tokens.css", css],
    ["components.json", manifest],
]) {
    if (check) {
        const actual = await readFile(new URL(name, base), "utf8");
        // Editor formatting must not be mistaken for a token change.
        if (name.endsWith(".json")) assert.deepEqual(JSON.parse(actual), JSON.parse(content));
        else assert.ok(actual.replace(/\s/g, "").toLowerCase() === content.replace(/\s/g, "").toLowerCase(), `${name} is stale; run npm run design-system:generate`);
    } else await writeFile(new URL(name, base), content);
}

const luminance = (hex) => {
    const values = hex
        .slice(1)
        .match(/../g)
        .map((v) => parseInt(v, 16) / 255)
        .map((v) => (v <= 0.04045 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4));
    return values[0] * 0.2126 + values[1] * 0.7152 + values[2] * 0.0722;
};
let pairs = 0;
for (const [theme, colors] of Object.entries(tokens.themes)) {
    const contrast = (fg, bg, minimum) => {
        const a = luminance(colors[fg]),
            b = luminance(colors[bg]);
        assert.ok(
            (Math.max(a, b) + 0.05) / (Math.min(a, b) + 0.05) >= minimum,
            `${theme}: ${fg} / ${bg}`,
        );
        pairs++;
    };
    for (const text of ["primary", "secondary", "muted"])
        contrast(`text-${text}`, "surface-default", 4.5);
    for (const state of ["default", "hover", "pressed"])
        contrast("action-on", `action-${state}`, 4.5);
    for (const status of ["success", "warning", "danger", "info"])
        contrast(`status-${status}-text`, `status-${status}-background`, 4.5);
    contrast("border-control", "surface-default", 3);
}
console.log(
    `${check ? "Verified" : "Generated"} design system: 30 specifications, nine type levels, ${pairs} contrast pairs.`,
);
